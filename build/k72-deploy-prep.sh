#!/bin/bash
# k72-deploy-prep.sh - two things before staging: (1) does the patched probe
# still assign ctx->dev (the driver uses it everywhere), (2) what does the
# current boot.ini look like so I can generate a 7.2.8 variant with literal
# file names (u-boot 2017.09 cannot expand ${var} inside a file name).
set -uo pipefail
K=/root/r36/linux-7.2.8
P=$K/drivers/gpu/drm/panel/panel-generic-dsi.c

echo "=== ctx->dev assignment sites ==="
grep -n "ctx->dev *=" "$P" | sed 's/^/  /' || echo "  NONE - the patch must add it"
echo "  (probe body, first 14 lines after the alloc)"
sed -n '618,634p' "$P" | sed 's/^/    /'

echo "=== current boot.ini as generated by pack-v10.sh ==="
grep -n -A22 "boot.ini" /mnt/e/ubuntu/build/pack-v10.sh | sed -n '1,40p'

echo "=== 7.2.8 artifacts ready? ==="
ls -l "$K/arch/arm64/boot/Image" \
      "$K/arch/arm64/boot/dts/rockchip/rk3326-xifan-r36max2.dtb" 2>&1 | sed 's/^/  /'
ls -l /root/r36/out72/lib/modules/7.2.8 2>/dev/null | head -4 | sed 's/^/  /'
ls -l /root/r36/k72test/wifi/drivers/aic8800/*/*.ko 2>/dev/null | sed 's/^/  /'
echo "=== prep done ==="
